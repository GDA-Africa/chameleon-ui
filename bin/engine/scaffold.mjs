/**
 * Chameleon Engine — filesystem scaffolding operations (F59).
 * All functions return the Result shape from core.mjs. No printing, no exits.
 */

import fs from "fs";
import path from "path";
import {
  COMPONENTS, TEMPLATES, VALID_THEMES, LOCAL_DEPS_COMPONENTS, LOCAL_DEPS_TEMPLATES, componentExport,
} from "./registry.mjs";
import {
  makeResult, addError, evOk, evWarn, evInfo, evDim, requireConfig, readConfig, writeConfig, readProjectPkg,
} from "./core.mjs";

const rewriteImports = (content) => content.replace(/from\s+['"]\.\/.*?['"]/g, 'from "@chameleon-ui-lib/react"');

/** Scaffold one component into cfg.dir. Emits events onto `r`. Returns info or null. */
function scaffoldOne(ctx, cfg, key, r, { verbose = true } = {}) {
  const meta = COMPONENTS[key];
  if (!meta) return null;
  const srcFile = path.join(ctx.libSrc, meta.file);
  const outDir  = path.join(ctx.cwd, cfg.dir);
  if (!fs.existsSync(srcFile)) {
    addError(r, "SOURCE_NOT_FOUND", `Source file not found: ${meta.file}`);
    r.events.push({ level: "error", message: `Source file not found: ${meta.file}` });
    return null;
  }
  fs.mkdirSync(outDir, { recursive: true });
  let content = fs.readFileSync(srcFile, "utf8");
  const foundDeps = LOCAL_DEPS_COMPONENTS.filter(
    (dep) => content.includes(`from "./${dep}"`) || content.includes(`from './${dep}'`),
  );
  content = rewriteImports(content);
  fs.writeFileSync(path.join(outDir, `${key}.tsx`), content, "utf8");
  r.filesWritten.push(`${cfg.dir}/${key}.tsx`);
  if (verbose) {
    evOk(r, `${cfg.dir}/${key}.tsx created`);
    if (meta.deps.length > 0) evInfo(r, `External deps: ${meta.deps.join(", ")}`);
    if (foundDeps.length > 0) evInfo(r, `Mapped: ${foundDeps.join(", ")} → @chameleon-ui-lib/react`);
  } else {
    evOk(r, `${cfg.dir}/${key}.tsx`);
  }
  return { key, pascalName: componentExport(key), file: `${key}.tsx`, externalDependencies: meta.deps };
}

/** Regenerate the barrel index.ts in cfg.dir. */
function regenerateBarrel(ctx, cfg, r) {
  const outDir = path.join(ctx.cwd, cfg.dir);
  if (!fs.existsSync(outDir)) return;
  const files = fs.readdirSync(outDir).filter((f) => f.endsWith(".tsx") && f !== "index.ts");
  if (files.length === 0) return;
  const lines = files.map((f) => `export * from './${f.replace(".tsx", "")}';`);
  fs.writeFileSync(path.join(outDir, "index.ts"), `// Auto-generated by Chameleon UI CLI — do not edit manually\n${lines.join("\n")}\n`, "utf8");
  r.filesWritten.push(`${cfg.dir}/index.ts`);
  evOk(r, `${cfg.dir}/index.ts updated (barrel export for ${files.length} component(s))`);
}

/**
 * Add components. `keys` is an array of component names; pass `bulk: true` for
 * the compact per-file event style used by --all-* flags.
 */
export function addComponents(ctx, keys, { bulk = false } = {}) {
  const r = makeResult();
  const cfg = requireConfig(ctx, r);
  if (!cfg) return r;
  const added = [];
  for (const rawKey of keys) {
    const key = String(rawKey).toLowerCase();
    if (!COMPONENTS[key]) {
      return addError(r, "UNKNOWN_COMPONENT", `Unknown component: '${rawKey}'. Run \`chameleon list --json\` for the catalog.`);
    }
    const one = scaffoldOne(ctx, cfg, key, r, { verbose: !bulk });
    if (one) added.push(one);
  }
  if (added.length > 0) regenerateBarrel(ctx, cfg, r);
  r.data = { added: added.map((a) => ({ name: a.key, export: a.pascalName, file: `${cfg.dir}/${a.file}`, externalDependencies: a.externalDependencies })) };
  if (added.length > 0) r.nextSteps.push(`Import via: import { ${added.map((a) => a.pascalName).join(", ")} } from '${cfg.dir}'`);
  r.data.dir = cfg.dir;
  return r;
}

/** Resolve bulk selection for --all-* flags; returns component keys. */
export function selectBulk(flag) {
  const filters = {
    "--all-atoms":      (v) => v.category === "Atom",
    "--all-molecules":  (v) => v.category === "Molecule",
    "--all-composites": (v) => v.category === "Composite",
    "--all":            () => true,
  };
  const f = filters[flag];
  if (!f) return null;
  return Object.entries(COMPONENTS).filter(([, v]) => f(v)).map(([k]) => k);
}

export function removeComponent(ctx, rawKey) {
  const r = makeResult();
  const cfg = requireConfig(ctx, r);
  if (!cfg) return r;
  const key = String(rawKey).toLowerCase();
  const outFile = path.join(ctx.cwd, cfg.dir, `${key}.tsx`);
  if (!fs.existsSync(outFile)) {
    evWarn(r, `${cfg.dir}/${key}.tsx not found — nothing to remove.`);
    r.data = { removed: null };
    return r;
  }
  fs.unlinkSync(outFile);
  r.filesDeleted.push(`${cfg.dir}/${key}.tsx`);
  evOk(r, `${cfg.dir}/${key}.tsx deleted`);
  r.data = { removed: key };
  return r;
}

export function scaffoldTemplate(ctx, rawKey) {
  const r = makeResult();
  const key = String(rawKey).toLowerCase();
  const meta = TEMPLATES[key];
  if (!meta) return addError(r, "UNKNOWN_TEMPLATE", `Unknown template: '${rawKey}'.`, { available: Object.keys(TEMPLATES) });
  const cfg = requireConfig(ctx, r);
  if (!cfg) return r;
  const srcFile  = path.join(ctx.libSrc, meta.file);
  const pagesDir = cfg.pagesDir || "src/pages";
  const outDir   = path.join(ctx.cwd, pagesDir);
  if (!fs.existsSync(srcFile)) return addError(r, "SOURCE_NOT_FOUND", `Source file not found: ${meta.file}`);
  fs.mkdirSync(outDir, { recursive: true });

  let content = fs.readFileSync(srcFile, "utf8");
  const foundDeps = LOCAL_DEPS_TEMPLATES.filter(
    (dep) => content.includes(`from "./${dep}"`) || content.includes(`from './${dep}'`),
  );
  content = rewriteImports(content);
  fs.writeFileSync(path.join(outDir, `${key}.tsx`), content, "utf8");
  r.filesWritten.push(`${pagesDir}/${key}.tsx`);

  evOk(r, `${pagesDir}/${key}.tsx created`);
  evOk(r, `Exported: ${meta.export}`);
  if (foundDeps.length > 0) evInfo(r, `Mapped local dependencies to package exports: ${foundDeps.join(", ")}`);
  r.nextSteps.push(`Import via: import { ${meta.export} } from './pages/${key}'`);
  r.data = { template: key, export: meta.export, file: `${pagesDir}/${key}.tsx` };
  return r;
}

export function setTheme(ctx, rawTheme) {
  const r = makeResult();
  if (!VALID_THEMES.includes(rawTheme)) {
    return addError(r, "INVALID_THEME", `Invalid theme: '${rawTheme}'.`, { validThemes: VALID_THEMES });
  }
  const cfg = requireConfig(ctx, r);
  if (!cfg) return r;
  cfg.theme = rawTheme;
  writeConfig(ctx, cfg, r);
  evOk(r, `chameleon.config.json updated → theme: ${rawTheme}`);
  r.data = { theme: rawTheme };
  return r;
}

export function updateComponents(ctx) {
  const r = makeResult();
  const cfg = requireConfig(ctx, r);
  if (!cfg) return r;
  const outDir = path.join(ctx.cwd, cfg.dir);
  const results = { updated: [], upToDate: [] };
  if (!fs.existsSync(outDir)) {
    evInfo(r, `No scaffolded components found in ${cfg.dir}`);
    r.data = results;
    return r;
  }
  for (const file of fs.readdirSync(outDir).filter((f) => f.endsWith(".tsx"))) {
    const key  = file.replace(".tsx", "").toLowerCase();
    const meta = COMPONENTS[key] || TEMPLATES[key];
    if (!meta) continue;
    const localPath  = path.join(outDir, file);
    const sourcePath = path.join(ctx.libSrc, meta.file);
    if (!fs.existsSync(sourcePath)) continue;
    const localContent = fs.readFileSync(localPath, "utf8");
    const sourceContent = rewriteImports(fs.readFileSync(sourcePath, "utf8"));
    if (localContent !== sourceContent) {
      fs.writeFileSync(localPath, sourceContent, "utf8");
      r.filesWritten.push(`${cfg.dir}/${file}`);
      evOk(r, `Updated ${file}`);
      results.updated.push(key);
    } else {
      evInfo(r, `${file} already up to date`);
      results.upToDate.push(key);
    }
  }
  r.data = results;
  return r;
}

/** Initialize a consumer project (config, dirs, Tailwind v4 wiring, CSS import). */
export function initProject(ctx, { version }) {
  const r = makeResult();
  const pkg = readProjectPkg(ctx);
  if (!pkg) return addError(r, "NO_PACKAGE_JSON", "No package.json found. Run this inside your project root.");
  evOk(r, "package.json found");

  const allDeps = { ...pkg.dependencies, ...pkg.devDependencies };
  if (allDeps["@chameleon-ui-lib/react"]) evOk(r, "@chameleon-ui-lib/react is installed");
  else evWarn(r, "@chameleon-ui-lib/react not found — run: npm install @chameleon-ui-lib/react");

  if (fs.existsSync(ctx.configFile)) {
    evWarn(r, "chameleon.config.json already exists — skipping");
  } else {
    writeConfig(ctx, { theme: "simple", mode: "light", lang: "en", dir: "src/components/ui", pagesDir: "src/pages", css: "src/styles/theme.css", version }, r);
    evOk(r, "chameleon.config.json created");
  }

  const cfg = readConfig(ctx);
  const outDir = path.join(ctx.cwd, cfg.dir);
  if (!fs.existsSync(outDir)) { fs.mkdirSync(outDir, { recursive: true }); evOk(r, `Created ${cfg.dir}`); }
  else evOk(r, `Output directory exists: ${cfg.dir}`);

  autoConfigureTailwindVite(ctx, r);
  checkCssTailwindImport(ctx, cfg.css || "src/index.css", r);

  r.nextSteps.push(
    'Ensure CSS entry starts with: @import "tailwindcss"; @import "@chameleon-ui-lib/react/styles";',
    'Wrap your app in <ChameleonProvider initialTheme="simple" initialMode="light">',
    "Run: chameleon add <component> / chameleon template <name> / chameleon doctor",
  );
  r.data = { config: cfg };
  return r;
}

function autoConfigureTailwindVite(ctx, r) {
  const viteConf = ["vite.config.ts", "vite.config.js", "vite.config.mjs"].find((f) => fs.existsSync(path.join(ctx.cwd, f)));
  if (!viteConf) {
    evWarn(r, "No Vite config found. Make sure to configure @tailwindcss/vite manually.");
    return false;
  }
  const confPath = path.join(ctx.cwd, viteConf);
  let content = fs.readFileSync(confPath, "utf8");

  if (content.includes("@tailwindcss/vite") || content.includes("tailwindcss()")) {
    evOk(r, `Tailwind v4 plugin already configured in ${viteConf}`);
    return true;
  }

  evDim(r, `Injecting Tailwind v4 Vite plugin into ${viteConf}...`);

  if (!content.includes("import tailwindcss")) {
    const importMatch = [...content.matchAll(/import\s+.*?from\s+['"][^'"]+['"];?/gs)];
    if (importMatch.length > 0) {
      const lastImport = importMatch[importMatch.length - 1][0];
      content = content.replace(lastImport, `${lastImport}\nimport tailwindcss from "@tailwindcss/vite";`);
    } else {
      content = `import tailwindcss from "@tailwindcss/vite";\n` + content;
    }
  }

  const pluginsMatch = content.match(/plugins:\s*\[(.*?)\]/s);
  if (pluginsMatch) {
    let currentPlugins = pluginsMatch[1].trim();
    if (currentPlugins && !currentPlugins.endsWith(",")) currentPlugins += ", ";
    const newPlugins = currentPlugins ? `${currentPlugins}tailwindcss()` : `tailwindcss()`;
    content = content.replace(/plugins:\s*\[.*?\]/s, `plugins: [${newPlugins}]`);
    fs.writeFileSync(confPath, content, "utf8");
    r.filesWritten.push(viteConf);
    evOk(r, `Successfully updated ${viteConf}`);
    return true;
  }
  evWarn(r, `Could not automatically add tailwindcss() to plugins in ${viteConf}. Add it manually.`);
  return false;
}

function checkCssTailwindImport(ctx, configCssPath, r) {
  const cssPath = path.join(ctx.cwd, configCssPath || "src/index.css");
  if (fs.existsSync(cssPath)) {
    let content = fs.readFileSync(cssPath, "utf8");
    if (!content.includes("@import 'tailwindcss'") && !content.includes('@import "tailwindcss"')) {
      content = `@import "tailwindcss";\n` + content;
      fs.writeFileSync(cssPath, content, "utf8");
      r.filesWritten.push(configCssPath || "src/index.css");
      evOk(r, `Injected @import "tailwindcss" into ${configCssPath}`);
    } else {
      evOk(r, `Tailwind directives found in ${configCssPath}`);
    }
  } else {
    evWarn(r, `CSS entry ${configCssPath} not found. Don't forget to add @import "tailwindcss".`);
  }
}
