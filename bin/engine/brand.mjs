/**
 * Chameleon Engine — brand token pipeline (F62/F65, Phase 12).
 *
 * brand.config.json is the persisted brand: colors, font, radius. It flows
 * into the UI via the ChameleonProvider `brand` prop (inline CSS vars — the
 * authoritative path) and a generated chameleon-brand.css (supplementary
 * :root layer for font/radius outside the provider).
 *
 * Extraction (from-url / from-logo) returns CANDIDATES with provenance —
 * never auto-applies. `brand check` is the WCAG AA safety net.
 */

import fs from "fs";
import path from "path";
import { URL } from "node:url";
import { makeResult, addError, evOk, evWarn, evInfo } from "./core.mjs";

// Node 18+ global fetch (undici)
const fetch = globalThis.fetch;

export const BRAND_FILE = "brand.config.json";
export const BRAND_CSS  = "chameleon-brand.css";
const HEX = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i;

// ── color math (mirrors library utils.ts behavior) ─────────────────────────
export function hexToRgb(hex) {
  let h = hex.replace("#", "");
  if (h.length === 3) h = h.split("").map((c) => c + c).join("");
  const n = parseInt(h, 16);
  return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255 };
}
const toHex = ({ r, g, b }) =>
  "#" + [r, g, b].map((v) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, "0")).join("");

export function luminance(hex) {
  const { r, g, b } = hexToRgb(hex);
  const f = (v) => { const s = v / 255; return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4); };
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
}

export function contrastRatio(a, b) {
  const [l1, l2] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (l1 + 0.05) / (l2 + 0.05);
}

/** Black or white — whichever contrasts more. */
export const contrastColor = (hex) => (contrastRatio(hex, "#ffffff") >= contrastRatio(hex, "#000000") ? "#ffffff" : "#000000");

const mix = (hex, target, amt) => {
  const c = hexToRgb(hex), t = hexToRgb(target);
  return toHex({ r: c.r + (t.r - c.r) * amt, g: c.g + (t.g - c.g) * amt, b: c.b + (t.b - c.b) * amt });
};
/** Light/dark variations of a brand color for mode-aware primaries. */
export const variations = (hex) => ({ light: mix(hex, "#ffffff", 0.25), dark: mix(hex, "#000000", 0.2) });

// ── brand init / check ───────────────────────────────────────────────────────
export function brandInit(ctx, opts = {}) {
  const r = makeResult();
  const { primaryColor, secondaryColor, accentColor, fontFamily, radius } = opts;
  if (!primaryColor || !HEX.test(primaryColor)) {
    return addError(r, "INVALID_BRAND", "brand init requires --primary <#hex> (3 or 6 digit).");
  }
  for (const [k, v] of Object.entries({ secondaryColor, accentColor })) {
    if (v && !HEX.test(v)) return addError(r, "INVALID_BRAND", `${k} must be a hex color, got '${v}'.`);
  }
  const brand = {
    version: 1,
    primaryColor,
    ...(secondaryColor ? { secondaryColor } : {}),
    ...(accentColor ? { accentColor } : {}),
    ...(fontFamily ? { fontFamily } : {}),
    ...(radius ? { radius } : {}),
  };
  fs.writeFileSync(path.join(ctx.cwd, BRAND_FILE), JSON.stringify(brand, null, 2) + "\n", "utf8");
  r.filesWritten.push(BRAND_FILE);
  evOk(r, `${BRAND_FILE} created`);

  const v = variations(primaryColor);
  const css = `/* Generated by \`chameleon brand init\` — supplementary layer.
 * The authoritative path is the ChameleonProvider \`brand\` prop:
 *   import brand from "./brand.config.json";
 *   <ChameleonProvider brand={brand} ...>
 */
:root {
${fontFamily ? `  --brand-font: "${fontFamily}", system-ui, sans-serif;\n` : ""}${radius ? `  --radius: ${radius};\n` : ""}  --brand-primary: ${primaryColor};
  --brand-primary-light: ${v.light};
  --brand-primary-dark: ${v.dark};
  --brand-primary-foreground: ${contrastColor(primaryColor)};
}
${fontFamily ? `\nbody { font-family: var(--brand-font); }\n` : ""}`;
  fs.writeFileSync(path.join(ctx.cwd, BRAND_CSS), css, "utf8");
  r.filesWritten.push(BRAND_CSS);
  evOk(r, `${BRAND_CSS} generated`);

  const check = brandCheckData(brand);
  for (const c of check.checks) {
    (c.pass ? evOk : evWarn)(r, `${c.pair}: ${c.ratio.toFixed(2)}:1 ${c.pass ? "(AA ok)" : `(below ${c.required}:1)`}`);
  }
  if (!check.allPass) evWarn(r, "Some pairs are below WCAG AA — run `chameleon brand check --json` for details.");

  r.nextSteps.push(
    `Pass the brand to your provider: import brand from "./${BRAND_FILE}"; <ChameleonProvider brand={brand}>`,
    `Optionally import ./${BRAND_CSS} in your CSS entry for the font/radius layer`,
    "Verify legibility any time with: chameleon brand check",
  );
  r.data = { brand, contrast: check };
  return r;
}

export function readBrand(ctx) {
  const p = path.join(ctx.cwd, BRAND_FILE);
  if (!fs.existsSync(p)) return null;
  try { return JSON.parse(fs.readFileSync(p, "utf8")); } catch { return null; }
}

/** WCAG AA audit of a brand object (pure; no fs). */
export function brandCheckData(brand) {
  const checks = [];
  const pair = (name, fg, bg, required = 4.5) => {
    const ratio = contrastRatio(fg, bg);
    checks.push({ pair: name, fg, bg, ratio, required, pass: ratio >= required });
  };
  const p = brand.primaryColor;
  const v = variations(p);
  pair("primary on its foreground", contrastColor(p), p);
  pair("primary(light-variant) on its foreground", contrastColor(v.light), v.light);
  pair("primary(dark-variant) on its foreground", contrastColor(v.dark), v.dark);
  // Legibility against canonical surfaces (light/dark backgrounds)
  pair("primary on white surface", p, "#ffffff", 3.0);
  pair("primary(light-variant) on dark surface", v.light, "#0f172a", 3.0);
  if (brand.secondaryColor) pair("secondary on its foreground", contrastColor(brand.secondaryColor), brand.secondaryColor);
  if (brand.accentColor)    pair("accent on its foreground", contrastColor(brand.accentColor), brand.accentColor);
  return { checks, allPass: checks.every((c) => c.pass) };
}

export function brandCheck(ctx) {
  const r = makeResult();
  const brand = readBrand(ctx);
  if (!brand) return addError(r, "NO_BRAND", `No ${BRAND_FILE} found. Run \`chameleon brand init --primary <#hex>\` first.`);
  const data = brandCheckData(brand);
  for (const c of data.checks) {
    (c.pass ? evOk : evWarn)(r, `${c.pair}: ${c.ratio.toFixed(2)}:1 ${c.pass ? "(AA ok)" : `(below ${c.required}:1)`}`);
  }
  r.ok = data.allPass;
  if (!data.allPass) r.errors.push({ code: "CONTRAST_FAIL", message: "One or more brand pairs are below WCAG AA." });
  r.data = { brand, ...data };
  return r;
}

// ── extraction: candidates with provenance, never auto-applied ──────────────
const NAMED = { black: "#000000", white: "#ffffff", red: "#ff0000", blue: "#0000ff", green: "#008000" };

function collectColors(text, source, tally) {
  for (const m of text.matchAll(/#([0-9a-f]{6}|[0-9a-f]{3})\b/gi)) {
    let hex = m[0].toLowerCase();
    if (hex.length === 4) hex = "#" + hex.slice(1).split("").map((c) => c + c).join("");
    const e = tally.get(hex) || { color: hex, count: 0, sources: new Set() };
    e.count++; e.sources.add(source);
    tally.set(hex, e);
  }
}

/** Extract brand candidates from a URL (HTML + inline/linked CSS heuristics). */
export async function brandFromUrl(url) {
  const r = makeResult();
  let html;
  try {
    const res = await fetch(url, { redirect: "follow" });
    if (!res.ok) return addError(r, "FETCH_FAILED", `Fetch failed: ${res.status} ${res.statusText}`);
    html = await res.text();
  } catch (e) {
    return addError(r, "FETCH_FAILED", `Could not fetch ${url}: ${e.message}`);
  }
  const tally = new Map();
  collectColors(html, "html", tally);
  // linked stylesheets (same-origin resolution, max 3)
  const links = [...html.matchAll(/<link[^>]+rel=["']stylesheet["'][^>]*href=["']([^"']+)["']/gi)].slice(0, 3);
  for (const [, href] of links) {
    try {
      const cssUrl = new URL(href, url).toString();
      const css = await (await fetch(cssUrl)).text();
      collectColors(css, path.basename(new URL(cssUrl).pathname) || "css", tally);
    } catch { /* skip unreachable sheets */ }
  }
  const fonts = [...new Set([...html.matchAll(/font-family:\s*['"]?([A-Za-z][A-Za-z0-9 ]+)/g)].map((m) => m[1].trim()))]
    .filter((f) => !/^(inherit|initial|sans-serif|serif|monospace|system-ui)$/i.test(f)).slice(0, 5);
  const colors = [...tally.values()]
    .filter((c) => !["#000000", "#ffffff"].includes(c.color))
    .sort((a, b) => b.count - a.count).slice(0, 8)
    .map((c) => ({ color: c.color, occurrences: c.count, sources: [...c.sources] }));
  evInfo(r, `Extracted ${colors.length} color candidate(s) and ${fonts.length} font candidate(s) from ${url}`);
  r.nextSteps.push("Candidates only — confirm a palette, then run: chameleon brand init --primary <#hex> [--font <name>]");
  r.data = { url, colorCandidates: colors, fontCandidates: fonts };
  return r;
}

/** Extract color candidates from an SVG logo (fills/strokes; no image decoding). */
export function brandFromLogo(ctx, file) {
  const r = makeResult();
  const p = path.resolve(ctx.cwd, file);
  if (!fs.existsSync(p)) return addError(r, "FILE_NOT_FOUND", `Logo not found: ${file}`);
  if (!p.toLowerCase().endsWith(".svg")) {
    return addError(r, "UNSUPPORTED_FORMAT", "from-logo currently supports SVG logos (raster quantization is on the roadmap). Export your logo as SVG or use from-url.");
  }
  const svg = fs.readFileSync(p, "utf8");
  const tally = new Map();
  collectColors(svg, path.basename(p), tally);
  for (const [name, hex] of Object.entries(NAMED)) {
    const count = (svg.match(new RegExp(`(fill|stroke)=["']${name}["']`, "gi")) || []).length;
    if (count) {
      const e = tally.get(hex) || { color: hex, count: 0, sources: new Set() };
      e.count += count; e.sources.add(path.basename(p));
      tally.set(hex, e);
    }
  }
  const colors = [...tally.values()].sort((a, b) => b.count - a.count).slice(0, 6)
    .map((c) => ({ color: c.color, occurrences: c.count, sources: [...c.sources] }));
  if (colors.length === 0) return addError(r, "NO_COLORS", "No explicit colors found in the SVG (CSS-classed fills are not resolved).");
  evInfo(r, `Extracted ${colors.length} color candidate(s) from ${file}`);
  r.nextSteps.push("Candidates only — confirm, then run: chameleon brand init --primary <#hex>");
  r.data = { file, colorCandidates: colors };
  return r;
}
